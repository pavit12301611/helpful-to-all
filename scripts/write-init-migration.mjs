#!/usr/bin/env node
/**
 * Writes the initial PostgreSQL migration SQL from prisma/schema.prisma so that
 * `prisma migrate deploy` can provision a fresh database (including in
 * environments that cannot download Prisma's engine binaries).
 *
 * Output: prisma/migrations/0001_init/migration.sql
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { loadSchemaModels, generateDdl } from './lib/prisma-ddl.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'prisma', 'migrations', '0001_init');
mkdirSync(outDir, { recursive: true });

const models = loadSchemaModels();
const sql = generateDdl(models, 'postgresql');
const header = `-- OpenHub initial schema (PostgreSQL)
-- Generated by scripts/write-init-migration.mjs from prisma/schema.prisma.
-- Apply with: npx prisma migrate deploy
`;

writeFileSync(join(outDir, 'migration.sql'), header + sql, 'utf8');
console.log(`[write-init-migration] wrote prisma/migrations/0001_init/migration.sql (${models.length} models)`);
